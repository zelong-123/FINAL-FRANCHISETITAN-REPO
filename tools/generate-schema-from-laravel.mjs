// One-shot generator: reads a SQLite file produced by running the original Laravel
// migrations + seeders, and writes the Postgres migrations and seed.sql.
// Usage: node tools/generate-schema-from-laravel.mjs <schema.sqlite> <supabase-dir>
// The generated SQL is the source of truth from now on; this is kept for traceability.
import { DatabaseSync } from 'node:sqlite';
import { createHash } from 'node:crypto';
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [sqlitePath, outDir] = process.argv.slice(2);
const db = new DatabaseSync(sqlitePath, { readOnly: true });

// Laravel plumbing that Supabase replaces (Auth tokens, sessions, cache, queues).
const SKIP_TABLES = new Set([
  'api_tokens', 'cache', 'cache_locks', 'failed_jobs', 'job_batches', 'jobs',
  'migrations', 'password_reset_tokens', 'sessions',
]);
// Credentials move to auth.users; nothing else may hold them.
const SKIP_COLUMNS = { users: new Set(['password', 'remember_token']) };
// Reference data the app cannot run without (everything else seeded is demo data).
const REFERENCE_TABLES = ['roles', 'units'];
const APP_TZ_OFFSET = '+08'; // config/app.php: Asia/Manila — Laravel stored naive local time.

const q = (id) => `"${id}"`;
const lit = (s) => `'${String(s).replace(/'/g, "''")}'`;

function pgType(declared) {
  const t = declared.toLowerCase();
  if (t.startsWith('decimal')) return t.replace('decimal', 'numeric');
  if (t === 'timestamp' || t === 'datetime') return 'timestamptz';
  if (t === 'json' || t === 'jsonb') return 'jsonb';
  if (t === 'varchar' || t === 'text' || t.startsWith('varchar')) return 'text';
  if (['bigint', 'integer', 'smallint', 'boolean', 'date', 'time'].includes(t)) return t;
  if (t === 'float' || t === 'double' || t === 'real') return 'double precision';
  throw new Error(`Unmapped column type: ${declared}`);
}

function pgDefault(col, type) {
  const raw = col.dflt_value;
  if (raw === null || raw === undefined || /^null$/i.test(raw)) return null;
  if (/^current_timestamp$/i.test(raw)) return 'now()';
  const unquoted = raw.replace(/^'(.*)'$/s, '$1');
  if (type === 'boolean') return ['1', 'true'].includes(unquoted.toLowerCase()) ? 'true' : 'false';
  if (type === 'jsonb') return `${lit(unquoted)}::jsonb`;
  if (['bigint', 'integer', 'smallint', 'double precision'].includes(type) || type.startsWith('numeric')) return unquoted;
  return lit(unquoted);
}

function shortName(name) {
  if (name.length <= 63) return name;
  return `${name.slice(0, 54)}_${createHash('sha1').update(name).digest('hex').slice(0, 8)}`;
}

const tables = db.prepare("select name from sqlite_master where type='table' and name not like 'sqlite_%' order by name").all()
  .map((t) => t.name).filter((n) => !SKIP_TABLES.has(n));

const meta = {};
for (const name of tables) {
  const skip = SKIP_COLUMNS[name] || new Set();
  const cols = db.prepare(`pragma table_xinfo(${q(name)})`).all();
  if (cols.some((c) => c.hidden)) throw new Error(`${name} has generated columns; handle explicitly`);
  meta[name] = {
    cols: cols.filter((c) => !skip.has(c.name)).map((c) => ({ ...c, pg: pgType(c.type) })),
    fks: db.prepare(`pragma foreign_key_list(${q(name)})`).all().filter((f) => !SKIP_TABLES.has(f.table)),
    indexes: db.prepare(`pragma index_list(${q(name)})`).all(),
  };
}

const out = [];
out.push('-- Generated from the Laravel migrations (54 files, final state). See tools/generate-schema-from-laravel.mjs.');
out.push('-- All access goes through the `api` Edge Function; browsers never touch these tables directly.\n');
out.push(`create or replace function public.set_updated_at() returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end $$;\n`);

for (const name of tables) {
  const { cols } = meta[name];
  const pk = cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk);
  const lines = cols.map((c) => {
    if (pk.length === 1 && c.pk && c.type.toUpperCase() === 'INTEGER') {
      return `  ${q(c.name)} bigint generated by default as identity primary key`;
    }
    let line = `  ${q(c.name)} ${c.pg}`;
    let def = pgDefault(c, c.pg);
    if (!def && (c.name === 'created_at' || c.name === 'updated_at')) def = 'now()';
    if (def) line += ` default ${def}`;
    if (c.notnull || (c.pk && pk.length)) line += ' not null';
    return line;
  });
  if (name === 'users') lines.push('  "auth_user_id" uuid unique references auth.users(id) on delete set null');
  if (pk.length > 1 || (pk.length === 1 && pk[0].type.toUpperCase() !== 'INTEGER')) {
    lines.push(`  primary key (${pk.map((c) => q(c.name)).join(', ')})`);
  }
  out.push(`create table public.${q(name)} (\n${lines.join(',\n')}\n);`);
  out.push(`alter table public.${q(name)} enable row level security;`);
  if (cols.some((c) => c.name === 'updated_at')) {
    out.push(`create trigger set_updated_at before update on public.${q(name)} for each row execute function public.set_updated_at();`);
  }
  out.push('');
}

// MySQL lets a foreign key target any indexed columns; Postgres needs a unique key on them.
// Only composites that contain the target's primary key are accepted, because those are
// unique by construction. Anything else stops the generator for a human decision.
const uniqueKeys = {};
for (const name of tables) {
  const pk = meta[name].cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk).map((c) => c.name);
  uniqueKeys[name] = new Set([pk.join(',')]);
  for (const ix of meta[name].indexes.filter((i) => i.unique)) {
    uniqueKeys[name].add(db.prepare(`pragma index_info(${q(ix.name)})`).all().sort((a, b) => a.seqno - b.seqno).map((c) => c.name).join(','));
  }
}
const pkOf = (name) => meta[name].cols.filter((c) => c.pk > 0).sort((a, b) => a.pk - b.pk).map((c) => c.name);
out.push('-- Unique keys that composite foreign keys need in Postgres (each contains the primary key).');
for (const name of tables) {
  const byId = Map.groupBy(meta[name].fks, (f) => f.id);
  for (const parts of byId.values()) {
    const target = parts[0].table;
    const to = parts.sort((a, b) => a.seq - b.seq).map((p) => p.to ?? pkOf(target)[p.seq]);
    if (uniqueKeys[target].has(to.join(','))) continue;
    if (!pkOf(target).every((c) => to.includes(c))) throw new Error(`FK ${name} -> ${target}(${to}) is not unique by construction`);
    uniqueKeys[target].add(to.join(','));
    const iname = shortName(`${target}_${to.join('_')}_fk_target_key`);
    out.push(`create unique index ${q(iname)} on public.${q(target)} (${to.map(q).join(', ')});`);
    console.log(`fk-target unique: ${target}(${to.join(', ')}) for ${name}`);
  }
}
out.push('');

let fkCount = 0;
const fkLines = ['-- Foreign keys come last: every table and unique index they depend on exists by now.'];
for (const name of tables) {
  const byId = new Map();
  for (const fk of meta[name].fks) {
    if (!byId.has(fk.id)) byId.set(fk.id, []);
    byId.get(fk.id).push(fk);
  }
  for (const parts of byId.values()) {
    parts.sort((a, b) => a.seq - b.seq);
    const { table: target, on_delete: del, on_update: upd } = parts[0];
    const from = parts.map((p) => q(p.from)).join(', ');
    const to = parts.map((p) => q(p.to ?? pkOf(target)[p.seq])).join(', ');
    const cname = shortName(`${name}_${parts.map((p) => p.from).join('_')}_fkey`);
    let sql = `alter table public.${q(name)} add constraint ${q(cname)} foreign key (${from}) references public.${q(target)} (${to})`;
    if (del && del !== 'NO ACTION') sql += ` on delete ${del.toLowerCase()}`;
    if (upd && upd !== 'NO ACTION') sql += ` on update ${upd.toLowerCase()}`;
    fkLines.push(`${sql};`);
    fkCount++;
  }
}
out.push('');

let idxCount = 0;
out.push('-- Indexes (plus one per foreign key column that has none, which Postgres does not add for you).');
const indexedFirst = {};
for (const name of tables) {
  const skip = SKIP_COLUMNS[name] || new Set();
  indexedFirst[name] = new Set(meta[name].cols.filter((c) => c.pk === 1).map((c) => c.name));
  for (const ix of meta[name].indexes) {
    if (ix.origin === 'pk') continue;
    const columns = db.prepare(`pragma index_info(${q(ix.name)})`).all().sort((a, b) => a.seqno - b.seqno).map((c) => c.name);
    if (columns.some((c) => skip.has(c) || c === null)) continue;
    indexedFirst[name].add(columns[0]);
    const iname = ix.origin === 'u' ? `${name}_${columns.join('_')}_key` : ix.name;
    out.push(`create ${ix.unique ? 'unique ' : ''}index ${q(shortName(iname))} on public.${q(name)} (${columns.map(q).join(', ')});`);
    idxCount++;
  }
  for (const fk of meta[name].fks) {
    if (fk.seq === 0 && !indexedFirst[name].has(fk.from)) {
      indexedFirst[name].add(fk.from);
      out.push(`create index ${q(shortName(`${name}_${fk.from}_idx`))} on public.${q(name)} (${q(fk.from)});`);
      idxCount++;
    }
  }
}
out.push('', ...fkLines, '');
out.push(`-- Deny by default: RLS is on with no policies, and the API roles get no table access.
revoke all on all tables in schema public from anon, authenticated;
revoke all on all sequences in schema public from anon, authenticated;
revoke all on all functions in schema public from anon, authenticated;
alter default privileges in schema public revoke all on tables from anon, authenticated;
alter default privileges in schema public revoke all on sequences from anon, authenticated;
alter default privileges in schema public revoke all on functions from anon, authenticated;
`);

function sqlValue(v, col) {
  if (v === null || v === undefined) return 'null';
  const t = col.pg;
  if (t === 'boolean') return Number(v) ? 'true' : 'false';
  if (t === 'jsonb') return `${lit(v)}::jsonb`;
  if (t === 'timestamptz') return lit(`${String(v).replace(/\.\d+$/, '')}${APP_TZ_OFFSET}`);
  if (typeof v === 'number' || typeof v === 'bigint') return String(v);
  return lit(v);
}

function insertsFor(name) {
  const { cols } = meta[name];
  const rows = db.prepare(`select * from ${q(name)} order by 1`).all();
  if (!rows.length) return [];
  const names = cols.map((c) => q(c.name)).join(', ');
  const values = rows.map((r) => `  (${cols.map((c) => sqlValue(r[c.name], c)).join(', ')})`);
  const lines = [`insert into public.${q(name)} (${names}) overriding system value values\n${values.join(',\n')};`];
  const idCol = cols.find((c) => c.pk === 1 && c.type.toUpperCase() === 'INTEGER');
  if (idCol) lines.push(`select setval(pg_get_serial_sequence('public.${name}', '${idCol.name}'), (select max(${q(idCol.name)}) from public.${q(name)}));`);
  return lines;
}

// Parents first; a self reference (e.g. users.archived_by_user_id) is fine when null in seeds.
function topoOrder(names) {
  const remaining = new Set(names);
  const order = [];
  while (remaining.size) {
    const ready = [...remaining].filter((n) => meta[n].fks.every((f) => f.table === n || !remaining.has(f.table)));
    if (!ready.length) throw new Error(`FK cycle among seeded tables: ${[...remaining]}`);
    for (const n of ready) { order.push(n); remaining.delete(n); }
  }
  return order;
}

const seeded = tables.filter((n) => db.prepare(`select count(*) c from ${q(n)}`).get().c > 0);
const demo = topoOrder(seeded.filter((n) => !REFERENCE_TABLES.includes(n)));

mkdirSync(join(outDir, 'migrations'), { recursive: true });
writeFileSync(join(outDir, 'migrations', '20261107000001_schema.sql'), `${out.join('\n')}\n`);
writeFileSync(join(outDir, 'migrations', '20261107000002_reference_data.sql'),
  `-- Roles and units: required for the app to run in every environment.\n${REFERENCE_TABLES.flatMap(insertsFor).join('\n')}\n`);
writeFileSync(join(outDir, 'seed.sql'),
  `-- Demo data from the Laravel seeders. Development only. Sign-ins are created separately by\n-- scripts/create-auth-users.mjs, because passwords live in Supabase Auth.\n${demo.flatMap(insertsFor).join('\n')}\n`);

console.log(`tables=${tables.length} fks=${fkCount} indexes=${idxCount} seeded=${seeded.join(',')}`);
