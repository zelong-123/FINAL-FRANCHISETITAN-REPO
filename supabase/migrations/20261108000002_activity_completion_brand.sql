-- Phase 2: real activity completion (attendance, proof, Admin review) and the Brand
-- Confirmation step after Product Tasting. Additive only.

-- 1. What Sales submitted when completing an activity, and Admin's review of it.
alter table public."activity_schedules" add column if not exists "attended" boolean;
alter table public."activity_schedules" add column if not exists "actual_started_at" timestamptz;
alter table public."activity_schedules" add column if not exists "handler_name" text;
alter table public."activity_schedules" add column if not exists "no_show_reason" text;
alter table public."activity_schedules" add column if not exists "completion_submitted_at" timestamptz;
alter table public."activity_schedules" add column if not exists "completion_submitted_by_user_id" bigint;
alter table public."activity_schedules" add column if not exists "review_status" text;
alter table public."activity_schedules" add column if not exists "reviewed_by_user_id" bigint;
alter table public."activity_schedules" add column if not exists "reviewed_at" timestamptz;
alter table public."activity_schedules" add column if not exists "return_reason" text;
-- Product Tasting: the brand that was actually tasted (null on older rows = the applicant's brand).
alter table public."activity_schedules" add column if not exists "tasted_brand_id" bigint;
alter table public."activity_schedules" add constraint "activity_schedules_completion_submitted_by_fkey"
  foreign key ("completion_submitted_by_user_id") references public."users" ("id") on delete set null;
alter table public."activity_schedules" add constraint "activity_schedules_reviewed_by_fkey"
  foreign key ("reviewed_by_user_id") references public."users" ("id") on delete set null;
alter table public."activity_schedules" add constraint "activity_schedules_tasted_brand_fkey"
  foreign key ("tasted_brand_id") references public."brands" ("id") on delete set null;

-- 2. Brand Confirmation: one row per submission (a returned one stays as history).
create table if not exists public."applicant_brand_confirmations" (
  "id" bigint generated by default as identity primary key,
  "applicant_id" bigint not null references public."applicants" ("id") on delete cascade,
  "tasted_brand_id" bigint references public."brands" ("id") on delete set null,
  "final_brand_id" bigint not null references public."brands" ("id"),
  "confirmation_method" text not null,
  "confirmed_on" date not null,
  "notes" text not null,
  "change_reason" text,
  "retasting_required" boolean not null default false,
  "status" text not null default 'submitted',
  "submitted_by_user_id" bigint references public."users" ("id") on delete set null,
  "submitted_at" timestamptz not null default now(),
  "reviewed_by_user_id" bigint references public."users" ("id") on delete set null,
  "reviewed_at" timestamptz,
  "return_reason" text,
  "created_at" timestamptz default now(),
  "updated_at" timestamptz default now(),
  constraint "applicant_brand_confirmations_method_check" check ("confirmation_method" in ('in_person', 'call', 'message', 'written')),
  constraint "applicant_brand_confirmations_status_check" check ("status" in ('submitted', 'returned', 'confirmed'))
);
create index if not exists "applicant_brand_confirmations_applicant_idx" on public."applicant_brand_confirmations" ("applicant_id", "id");
alter table public."applicant_brand_confirmations" enable row level security;
create trigger set_updated_at before update on public."applicant_brand_confirmations" for each row execute function public.set_updated_at();

-- 3. The lock itself, on the applicant, so every brand-changing path can check it cheaply.
alter table public."applicants" add column if not exists "brand_locked_at" timestamptz;
alter table public."applicants" add column if not exists "brand_locked_by_user_id" bigint;
alter table public."applicants" add constraint "applicants_brand_locked_by_fkey"
  foreign key ("brand_locked_by_user_id") references public."users" ("id") on delete set null;
