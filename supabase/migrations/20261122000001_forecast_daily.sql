-- Estimated Requirement, daily model (Descriptive / Predictive, WMA / SES / Croston). Additive only:
-- new columns get their defaults, no existing value or row is changed, nothing is dropped. The weekly
-- settings columns stay in place and are simply no longer read.

-- 1. New settings (the single forecast_settings row gets these defaults; existing columns keep their values).
alter table public."forecast_settings" add column if not exists "lookback_open_days" smallint not null default 28;
alter table public."forecast_settings" add column if not exists "minimum_open_days" smallint not null default 14;
alter table public."forecast_settings" add column if not exists "adi_cutoff" numeric(5,2) not null default 1.32;
alter table public."forecast_settings" add column if not exists "cv2_cutoff" numeric(5,2) not null default 0.49;
alter table public."forecast_settings" add column if not exists "ses_alpha" numeric(4,2) not null default 0.2;
alter table public."forecast_settings" add column if not exists "croston_alpha" numeric(4,2) not null default 0.1;
alter table public."forecast_settings" add column if not exists "z_score" numeric(4,2) not null default 1.65;
alter table public."forecast_settings" add column if not exists "low_cover_days" numeric(5,2) not null default 4;
alter table public."forecast_settings" add column if not exists "overstock_days" numeric(5,2) not null default 14;
alter table public."forecast_settings" add column if not exists "method_switch_days" smallint not null default 3;
alter table public."forecast_settings" add column if not exists "stale_count_days" smallint not null default 7;

-- 2. The last announced demand class per branch material. The method itself is computed on every request
--    (stateless switch rule); this row only makes sure forecast.method_changed is audited once per change.
create table if not exists public."forecast_material_classes" (
  "id" bigint generated by default as identity primary key,
  "location_id" bigint not null references public."franchise_locations" ("id") on delete cascade,
  "material_id" bigint not null references public."profittrack_materials" ("id") on delete cascade,
  "pattern" text not null,
  "method" text not null,
  "adi" numeric(10,4),
  "cv2" numeric(10,4),
  "classified_on" date not null,
  "created_at" timestamptz default now(),
  "updated_at" timestamptz default now(),
  constraint "forecast_material_classes_unique" unique ("location_id", "material_id"),
  constraint "forecast_material_classes_pattern_check" check ("pattern" in ('smooth', 'erratic', 'intermittent', 'lumpy')),
  constraint "forecast_material_classes_method_check" check ("method" in ('wma', 'ses', 'croston'))
);
create index if not exists "forecast_material_classes_material_id_index" on public."forecast_material_classes" ("material_id");
alter table public."forecast_material_classes" enable row level security;
drop trigger if exists set_updated_at on public."forecast_material_classes";
create trigger set_updated_at before update on public."forecast_material_classes" for each row execute function public.set_updated_at();

-- 3. Optional perishable cap per branch material (null = no cap). Set by Logistics with the stock levels.
alter table public."profittrack_materials" add column if not exists "max_cover_days" smallint;
alter table public."profittrack_materials" drop constraint if exists "profittrack_materials_max_cover_days_check";
alter table public."profittrack_materials" add constraint "profittrack_materials_max_cover_days_check" check ("max_cover_days" is null or "max_cover_days" between 1 and 60);
